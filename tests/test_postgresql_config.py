from __future__ import annotations

import os
import unittest
from unittest.mock import patch

from inventory.persistence.config import DatabaseConfig
from inventory.persistence.database import load_schema


class PostgreSQLConfigurationTests(unittest.TestCase):
    def test_sqlite_remains_default_without_database_url(self) -> None:
        with patch(
            "inventory.persistence.config.load_environment"
        ), patch.dict(os.environ, {}, clear=True):
            config = DatabaseConfig.from_environment()

        self.assertEqual(config.backend, "sqlite")
        self.assertEqual(config.db_name, "inventory.db")

    def test_database_url_selects_postgresql_and_tls(self) -> None:
        with patch(
            "inventory.persistence.config.load_environment"
        ), patch.dict(
            os.environ,
            {"DATABASE_URL": "postgresql://user:pass@db.example:5432/inventory"},
            clear=True,
        ):
            config = DatabaseConfig.from_environment()

        self.assertEqual(config.backend, "postgresql")
        self.assertEqual(
            config.connection_string,
            "postgresql://user:pass@db.example:5432/inventory",
        )
        self.assertEqual(config.sslmode, "require")

    def test_invalid_database_url_is_rejected(self) -> None:
        with patch(
            "inventory.persistence.config.load_environment"
        ), patch.dict(os.environ, {"DATABASE_URL": "https://example.test"}, clear=True):
            with self.assertRaisesRegex(ValueError, "DATABASE_URL"):
                DatabaseConfig.from_environment()

    def test_postgresql_schema_uses_identity_columns(self) -> None:
        schema = load_schema("postgresql")

        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", schema)
        self.assertNotIn("AUTOINCREMENT", schema)
        self.assertIn("CREATE TABLE IF NOT EXISTS stock_transactions", schema)


if __name__ == "__main__":
    unittest.main()
